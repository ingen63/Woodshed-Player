// #58: tests of the network check (tool/network_free.dart) with staged inputs: hits, no hits, the allowed
// provider folder, the own-origin marker, pubspec.lock, the C++ core and the Content Security Policy.
// The pure functions are tested directly; the command line tool runs with `dart` on a staged repository
// in a temporary folder and once on this repository.
//
// Run: cd app && flutter test tool/network_free_test.dart   (or `make network-free`)
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import 'network_free.dart';

final _tool = File('${Directory.current.path}/tool/network_free.dart').path;
final _repo = Directory.current.parent.path;

/// Repository-relative "path:line" of each finding.
List<String> _where(List<Finding> found) => [
  for (final f in found) '${f.path}:${f.line}',
];

/// Minimal policy with the allowed connect-src and [script] as hash of the one inline script.
String _html({
  String connect =
      "'self' https://www.googleapis.com https://oauth2.googleapis.com "
      'https://accounts.google.com',
  String? scriptSrc,
  String script = "\n  console.log('start');\n",
}) {
  final hash = scriptSrc ?? scriptHash(script);
  return '<!DOCTYPE html>\n<html>\n<head>\n'
      '<meta http-equiv="Content-Security-Policy" content="default-src \'self\'; '
      "script-src 'self' $hash; connect-src $connect\">\n"
      '</head>\n<body>\n<script>$script</script>\n</body>\n</html>\n';
}

const _lock = '''
# Generated by pub
packages:
  async:
    dependency: transitive
    description:
      name: async
    version: "2.13.0"
  crypto:
    dependency: "direct main"
    version: "3.0.6"
sdks:
  dart: ">=3.9.0"
''';

/// Staged repository with clean files; [extra] maps relative paths to contents.
Directory _stage(Map<String, String> extra) {
  final dir = Directory.systemTemp.createTempSync('wp_network_free');
  addTearDown(() => dir.deleteSync(recursive: true));
  final files = {
    'app/pubspec.lock': _lock,
    'app/web/index.html': _html(),
    'app/lib/main.dart': "import 'dart:io';\n\nvoid main() {}\n",
    'core/src/engine.cpp': '#include <cmath>\nint f() { return 1; }\n',
    ...extra,
  };
  files.forEach((rel, text) {
    File('${dir.path}/$rel')
      ..createSync(recursive: true)
      ..writeAsStringSync(text);
  });
  return dir;
}

ProcessResult _run(String root) =>
    Process.runSync('dart', [_tool, '--root', root]);

void main() {
  group('#58/AK1 network code only in the provider modules', () {
    test('hits name file and line', () {
      const src =
          "import 'dart:io';\n"
          "import 'package:http/http.dart' as http;\n"
          '\n'
          'final c = HttpClient();\n'
          "final s = WebSocket.connect('wss://x');\n"
          "final t = Socket.connect('h', 1);\n";
      final found = scanAppSource('app/lib/a.dart', src);
      expect(_where(found), [
        'app/lib/a.dart:2',
        'app/lib/a.dart:4',
        'app/lib/a.dart:5',
        'app/lib/a.dart:6',
      ]);
      expect(found.first.toString(), contains('network package'));
      expect(found.first.toString(), contains(providerDir));
    });

    test('browser fetch, XMLHttpRequest and EventSource in JavaScript', () {
      const js =
          "const a = await fetch('https://x');\n"
          'const b = new XMLHttpRequest();\n'
          "const c = new EventSource('/e');\n"
          "navigator.sendBeacon('/b', d);\n";
      expect(_where(scanAppSource('app/web/x.js', js)), [
        'app/web/x.js:1',
        'app/web/x.js:2',
        'app/web/x.js:3',
        'app/web/x.js:4',
      ]);
    });

    test('package:web interop fetch and other network packages', () {
      expect(
        scanAppSource(
          'app/packages/p/lib/p.dart',
          'final r = web.window.fetch(url.toJS);\n'
              "export 'package:dio/dio.dart';\n"
              "import 'package:web_socket_channel/io.dart';\n",
        ),
        hasLength(3),
      );
    });

    test('no hit: plain code, comments, similar names', () {
      const src =
          '// HttpClient and WebSocket are only named here\n'
          '/* fetch(x) /* nested */ XMLHttpRequest */\n'
          '/// Uses no Socket.\n'
          'Future<bool> fetchAudio(Track t) async => false;\n'
          'node.connect(ctx.destination);\n'
          "final url = 'https://example.org'; // HttpClient\n"
          "import 'package:http_parser/http_parser.dart';\n";
      expect(scanAppSource('app/lib/a.dart', src), isEmpty);
    });

    test('a string keeps comment markers inside it', () {
      const src = "final u = 'a // b'; final c = HttpClient();\n";
      expect(_where(scanAppSource('app/lib/a.dart', src)), [
        'app/lib/a.dart:1',
      ]);
    });

    test('the provider folder may hold network code', () {
      const src = "import 'package:http/http.dart';\nfinal c = HttpClient();\n";
      expect(scanAppSource('${providerDir}google_drive.dart', src), isEmpty);
      expect(scanAppSource('${providerDir}peer/relay.dart', src), isEmpty);
      // only that folder: a look-alike next to it is checked
      expect(scanAppSource('app/lib/sync/providers.dart', src), hasLength(2));
      expect(
        scanAppSource('app/lib/sync/provider/google.dart', src),
        hasLength(2),
      );
    });

    test('own-origin marker allows fetch, not other network code', () {
      const marked =
          '// $ownOriginMarker, the WASM core next to the app\n'
          'final r = await web.window\n'
          "    .fetch('core.wasm'.toJS);\n";
      expect(scanAppSource('app/lib/a.dart', marked), isEmpty);
      const tooFar =
          '// $ownOriginMarker, too far away\n'
          '\n'
          '\n'
          "final r = fetch('x');\n";
      expect(_where(scanAppSource('app/lib/a.dart', tooFar)), [
        'app/lib/a.dart:4',
      ]);
      const client = '// $ownOriginMarker\nfinal c = HttpClient();\n';
      expect(scanAppSource('app/lib/a.dart', client), hasLength(1));
    });

    test('comments are blanked, line numbers stay', () {
      const src =
          "a /* x\ny */ b // c\n'// kept' r'\\' + \"\"\"\n// s\n\"\"\"\n<!-- h\n-->z";
      final out = stripComments(src);
      expect(out.split('\n'), hasLength(src.split('\n').length));
      expect(out, isNot(contains('x')));
      expect(out, isNot(contains(' c')));
      expect(out, contains("'// kept'"));
      expect(out, contains('// s'));
      expect(out, isNot(contains(' h')));
      expect(out, endsWith('z'));
    });

    test('scans app/lib, app/packages, app/web and the shipped web core', () {
      final dir = _stage({
        'app/lib/x/b.dart': 'final c = HttpClient();\n',
        'app/packages/p/lib/p.dart': 'final c = HttpClient();\n',
        'app/web/sw.js': "fetch('x');\n",
        'core/web/wp_worklet.js': 'new WebSocket(u);\n',
        // never scanned: build output, generated copies, other folders
        'app/build/web/main.dart.js': "fetch('x');\n",
        'app/.dart_tool/x.dart': 'HttpClient();\n',
        'app/web/wp_core/wp_worklet.js': 'new WebSocket(u);\n',
        'app/test/t.dart': 'HttpClient();\n',
        'core/web/browser_test.html': "<script>fetch('x')</script>\n",
      });
      expect(_where(checkRepository(dir.path).findings), [
        'app/lib/x/b.dart:1',
        'app/packages/p/lib/p.dart:1',
        'app/web/sw.js:1',
        'core/web/wp_worklet.js:1',
      ]);
    });
  });

  group('#58/AK2 blocked packages in pubspec.lock', () {
    test('reads the package names', () {
      expect(lockPackages(_lock), {'async', 'crypto'});
    });

    test('blocked packages are found with their line', () {
      final lock = _lock.replaceFirst(
        '  crypto:',
        '  firebase_analytics:\n    dependency: "direct main"\n'
            '  sentry_flutter:\n    version: "8.0.0"\n'
            '  amplitude_flutter:\n    version: "4.0.0"\n'
            '  mixpanel_flutter:\n    version: "2.0.0"\n'
            '  crypto:',
      );
      final found = checkLock('app/pubspec.lock', lock);
      expect(
        found.map((f) => f.what.split(' ')[2]),
        containsAll([
          'firebase_analytics',
          'sentry_flutter',
          'amplitude_flutter',
          'mixpanel_flutter',
        ]),
      );
      expect(found.first.line, 8);
    });

    test('exact names: look-alikes and names in values do not count', () {
      final lock = _lock.replaceFirst(
        '  crypto:',
        '  firebase_core_platform_interface:\n    version: "1.0.0"\n'
            '  sentry_like_logger:\n    description:\n      name: sentry\n'
            '  crypto:',
      );
      expect(checkLock('app/pubspec.lock', lock), isEmpty);
    });

    test('the list holds the named kinds', () {
      for (final p in [
        'firebase_core',
        'firebase_crashlytics',
        'firebase_remote_config',
        'sentry',
        'sentry_flutter',
        'amplitude_flutter',
        'mixpanel_flutter',
        'google_mobile_ads',
      ]) {
        expect(blockedPackages, contains(p));
      }
    });

    test('this repository uses none', () {
      final lock = File('$_repo/app/pubspec.lock').readAsStringSync();
      expect(lockPackages(lock), contains('crypto'));
      expect(checkLock('app/pubspec.lock', lock), isEmpty);
    });
  });

  group('#58/AK3 no network calls in the C++ core', () {
    test('hits name file and line', () {
      const src =
          '#include <sys/socket.h>\n'
          '#include <netdb.h>\n'
          'int s = socket(AF_INET, SOCK_STREAM, 0);\n'
          'connect(s, addr, len);\n'
          'getaddrinfo(host, nullptr, &hints, &res);\n'
          'CURL *c = curl_easy_init();\n'
          '#include "curl/curl.h"\n'
          'NSURLSession *s = [NSURLSession sharedSession];\n';
      expect(scanCoreSource('core/src/net.cpp', src), hasLength(8));
      expect(
        scanCoreSource('core/src/net.cpp', src).first.toString(),
        'core/src/net.cpp:1: includes a network header (no network in the core)',
      );
    });

    test('no hit: similar names and comments', () {
      const src =
          '// socket(), connect() and curl_easy_init() are not used\n'
          'void disconnect();\n'
          'bool connected = reconnect_count > 0;\n'
          'NSURL *url = [NSURL fileURLWithPath:path];\n'
          '#include <cmath>\n';
      expect(scanCoreSource('core/src/a.cpp', src), isEmpty);
    });

    test('only core/src and core/include, never third_party', () {
      final dir = _stage({
        'core/include/wp.h': 'int connect(int);\n',
        'core/src/a.mm': 'nw_connection_t c;\n',
        'core/third_party/lib/net.c': 'socket(1, 2, 3);\n',
        'core/tests/t.cpp': 'socket(1, 2, 3);\n',
      });
      expect(_where(checkRepository(dir.path).findings), [
        'core/src/a.mm:1',
        'core/include/wp.h:1',
      ]);
    });
  });

  group('#58/AK4 Content Security Policy of the web app', () {
    test('a policy with the allowed hosts passes', () {
      expect(checkCsp('i.html', _html()), isEmpty);
    });

    test('missing policy, extra host, missing host', () {
      expect(
        checkCsp('i.html', '<html><head></head></html>').single.what,
        contains('no Content-Security-Policy'),
      );
      expect(
        checkCsp(
          'i.html',
          '<!-- <meta http-equiv="Content-Security-Policy" content="default-src \'self\'"> -->',
        ).single.what,
        contains('no Content-Security-Policy'),
      );
      final extra = checkCsp(
        'i.html',
        _html(
          connect: "'self' https://www.googleapis.com https://evil.example",
        ),
      );
      expect(extra.map((f) => f.what).join('\n'), contains('https://evil'));
      expect(extra.map((f) => f.what).join('\n'), contains('missing'));
      expect(extra.first.line, 4);
      expect(
        checkCsp('i.html', _html(connect: '*')).first.what,
        contains('more: *'),
      );
    });

    test('#71/AK1 a Dropbox host is no longer allowed', () {
      const dropbox = 'https://api.dropboxapi.com';
      expect(allowedConnectSrc.any((h) => h.contains('dropbox')), isFalse);
      final found = checkCsp(
        'i.html',
        _html(
          connect:
              "'self' https://www.googleapis.com https://oauth2.googleapis.com "
              'https://accounts.google.com $dropbox',
        ),
      );
      expect(found.single.what, contains(dropbox));
    });

    test('an inline script without its hash is named with the new hash', () {
      final found = checkCsp('i.html', _html(scriptSrc: "'sha256-old='"));
      expect(found.single.line, 7);
      expect(
        found.single.what,
        contains(scriptHash("\n  console.log('start');\n")),
      );
    });

    test(
      'the web app allows exactly its own origin and Google (#71/AK1, #55)',
      () {
        final html = File('$_repo/app/web/index.html').readAsStringSync();
        final d = cspDirectives(cspOf(html)!);
        expect(d['connect-src']!.toSet(), {
          "'self'",
          'https://www.googleapis.com',
          'https://oauth2.googleapis.com',
          'https://accounts.google.com',
        });
        expect(d['connect-src'], hasLength(4));
        expect(d['default-src'], ["'self'"]);
        expect(d['object-src'], ["'none'"]);
        expect(d['script-src'], isNot(contains("'unsafe-inline'")));
        expect(d['script-src'], isNot(contains("'unsafe-eval'")));
        expect(checkCsp('app/web/index.html', html), isEmpty);
      },
    );

    test('the policy comes before the inline script', () {
      final html = File('$_repo/app/web/index.html').readAsStringSync();
      expect(
        html.indexOf('Content-Security-Policy'),
        lessThan(html.indexOf('<script>')),
      );
    });
  });

  group('#58/AK6 command line', () {
    test('clean repository: exit 0', () {
      final r = _run(_stage({}).path);
      expect(r.exitCode, 0, reason: '${r.stdout}${r.stderr}');
      expect(r.stdout, contains('network-free: ok'));
    });

    test('a hit: exit 1, file and line', () {
      final r = _run(
        _stage({
          'app/lib/sync/cloud.dart':
              "import 'dart:io';\n\nfinal c = HttpClient();\n",
        }).path,
      );
      expect(r.exitCode, 1);
      expect(r.stdout, contains('app/lib/sync/cloud.dart:3: HttpClient'));
      expect(r.stdout, contains('1 finding(s)'));
    });

    test('the same code in the provider folder: exit 0', () {
      final r = _run(
        _stage({
          '${providerDir}google_drive.dart': "import 'package:http/http.dart' as http;\nfinal c = HttpClient();\n",
        }).path,
      );
      expect(r.exitCode, 0, reason: '${r.stdout}');
    });

    test('missing pubspec.lock: exit 2', () {
      final dir = _stage({});
      File('${dir.path}/app/pubspec.lock').deleteSync();
      final r = _run(dir.path);
      expect(r.exitCode, 2);
      expect(r.stderr, contains('pubspec.lock'));
    });

    test('wrong usage: exit 2', () {
      final r = Process.runSync('dart', [_tool, '--bogus']);
      expect(r.exitCode, 2);
    });

    test('this repository is network-free', () {
      final r = _run(_repo);
      expect(r.exitCode, 0, reason: '${r.stdout}${r.stderr}');
    });
  });
}
